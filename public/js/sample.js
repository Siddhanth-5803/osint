function stamp(day, hm) {
  const d = new Date(2026, 1, 2 + day); // starts 2 Feb 2026
  const dd = String(d.getDate()).padStart(2, "0");
  const mm = String(d.getMonth() + 1).padStart(2, "0");
  return `${dd}/${mm}/${d.getFullYear()}, ${hm}`;
}

